package com.codecrafthub.model;

import com.fasterxml.jackson.annotation.JsonCreator;
import com.fasterxml.jackson.annotation.JsonFormat;
import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import com.fasterxml.jackson.annotation.JsonInclude;
import com.fasterxml.jackson.annotation.JsonProperty;
import com.fasterxml.jackson.annotation.JsonValue;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;

import java.time.Instant;
import java.time.LocalDate;

/**
 * Represents a course in CodeCraftHub.
 */
@JsonIgnoreProperties(ignoreUnknown = false)
@JsonInclude(JsonInclude.Include.ALWAYS)
public class Course {

    /**
     * The ID is generated by the application.
     * It is read-only in JSON requests.
     */
    @JsonProperty(value = "id", access = JsonProperty.Access.READ_ONLY)
    private Long id;

    /**
     * Course name is required.
     */
    @NotBlank(message = "name is required")
    @JsonProperty("name")
    private String name;

    /**
     * Course description is required.
     */
    @NotBlank(message = "description is required")
    @JsonProperty("description")
    private String description;

    /**
     * The JSON field is called target_date,
     * while the Java field is called targetDate.
     */
    @NotNull(message = "target_date is required")
    @JsonFormat(shape = JsonFormat.Shape.STRING, pattern = "yyyy-MM-dd")
    @JsonProperty("target_date")
    private LocalDate targetDate;

    /**
     * Status must be one of the values defined in CourseStatus.
     */
    @NotNull(message = "status is required")
    @JsonProperty("status")
    private CourseStatus status;

    /**
     * Created automatically by the application.
     * It cannot be set by a client request.
     */
    @JsonProperty(value = "created_at", access = JsonProperty.Access.READ_ONLY)
    @JsonFormat(shape = JsonFormat.Shape.STRING)
    private Instant createdAt;

    public Course() {
        // Required by Jackson when reading JSON.
    }

    public Course(
            Long id,
            String name,
            String description,
            LocalDate targetDate,
            CourseStatus status,
            Instant createdAt) {

        this.id = id;
        this.name = name;
        this.description = description;
        this.targetDate = targetDate;
        this.status = status;
        this.createdAt = createdAt;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public LocalDate getTargetDate() {
        return targetDate;
    }

    public void setTargetDate(LocalDate targetDate) {
        this.targetDate = targetDate;
    }

    public CourseStatus getStatus() {
        return status;
    }

    public void setStatus(CourseStatus status) {
        this.status = status;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(Instant createdAt) {
        this.createdAt = createdAt;
    }

    /**
     * Defines the only valid status values.
     *
     * @JsonValue controls how values are written to JSON.
     * @JsonCreator controls how values are read from JSON.
     */
    public enum CourseStatus {

        NOT_STARTED("Not Started"),
        IN_PROGRESS("In Progress"),
        COMPLETED("Completed");

        private final String value;

        CourseStatus(String value) {
            this.value = value;
        }

        @JsonValue
        public String getValue() {
            return value;
        }

        @JsonCreator
        public static CourseStatus fromValue(String value) {
            for (CourseStatus status : CourseStatus.values()) {
                if (status.value.equals(value)) {
                    return status;
                }
            }

            /*
             * This exception is converted into a helpful HTTP 400 response
             * by GlobalExceptionHandler.
             */
            throw new IllegalArgumentException(
                    "Invalid status. Allowed values are: "
                            + "\"Not Started\", \"In Progress\", \"Completed\""
            );
        }
    }
}

